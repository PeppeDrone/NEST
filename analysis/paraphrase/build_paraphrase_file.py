def main():
    clips = pd.read_csv(CLIPS)
    counts = clips.groupby("manual_prompt").agg(n_clips=("clip_id", "size"), caption_type=("caption_type_manual", "first"))
    originals = [p[0] for p in PARAPHRASES]
    missing = set(counts.index) - set(originals)
    extra = set(originals) - set(counts.index)
    if missing or extra or len(originals) != len(set(originals)):
        raise SystemExit(f"caption coverage mismatch: missing={sorted(missing)} extra={sorted(extra)}")
    items = []
    for i, (orig, a, b) in enumerate(PARAPHRASES, start=1):
        items.append({"caption_id": f"c{i:02d}", "original": orig, "caption_type_manual": counts.loc[orig, "caption_type"],
                      "n_test_clips": int(counts.loc[orig, "n_clips"]), "paraphrase_A": a, "paraphrase_B": b})
    payload = {
        "format": "neomotion.paraphrase_set.v1",
        "version": 1,
        "split": "test",
        "source": "distinct manual captions of the locked test split (analysis/artifacts/test_partA/teacher/clips.csv)",
        "author": {"model": "Claude Opus 5.5", "model_id": "claude-opus-5-5", "provider": "Anthropic",
                   "date": "2026-10-08", "procedure": "single pass, written without consulting the parser source; not edited after freezing"},
        "rules": RULES,
        "n_captions": len(items), "n_paraphrases": 2 * len(items), "n_test_clips": int(counts.n_clips.sum()),
        "items": items,
    }
    out = HERE / "paraphrases_v1.json"
    text = json.dumps(payload, indent=2, ensure_ascii=False) + "\n"
    if out.exists() and out.read_text() != text:
        raise SystemExit(f"{out} exists with different content; frozen files are never overwritten (write v2)")
    out.write_text(text)
    digest = hashlib.sha256(text.encode()).hexdigest()
    (HERE / "paraphrases_v1.sha256").write_text(f"{digest}  paraphrases_v1.json\n")
    print(f"froze {len(items)} captions x 2 paraphrases -> {out.name}  sha256={digest}")


if __name__ == "__main__":
    main()
